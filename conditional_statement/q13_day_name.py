# C. if-elif-else - Q13. Day number to day name (1-5)
day = int(input("Enter day number (1-5): "))
if day == 1:
    print("Monday")
elif day == 2:
    print("Tuesday")
elif day == 3:
    print("Wednesday")
elif day == 4:
    print("Thursday")
elif day == 5:
    print("Friday")
else:
    print("Other")
